"""
Copies the U8g2 fonts the firmware draws with into the simulator, byte for byte.

The simulator decodes them with the same algorithm as U8g2, so its screen matches the
OLED pixel for pixel. Run it again if display.cpp starts using another font.

The U8g2 sources come with the firmware build: run `pio run` in firmware/ once first.

Usage:
    python tools/extract_u8g2_fonts.py
"""

import base64
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS_C = ROOT / "firmware/.pio/libdeps/esp32dev/U8g2/src/clib/u8g2_fonts.c"
OUTPUT = ROOT / "simulator/js/fonts.js"

# The fonts used in firmware/src/display.cpp
FONTS = ["u8g2_font_logisoso24_tr", "u8g2_font_6x10_tf", "u8g2_font_5x7_tf"]

ESCAPES = {"n": 10, "t": 9, "r": 13, "\\": 92, '"': 34, "'": 39, "?": 63}


def c_string_bytes(literal: str) -> bytes:
    """The bytes of one C string literal body (without the quotes)."""
    out = bytearray()
    i = 0
    while i < len(literal):
        c = literal[i]
        if c != "\\":
            out.append(ord(c))
            i += 1
            continue
        octal = re.match(r"[0-7]{1,3}", literal[i + 1:])
        if octal:
            out.append(int(octal.group(), 8))
            i += 1 + len(octal.group())
        else:
            out.append(ESCAPES[literal[i + 1]])
            i += 2
    return bytes(out)


def font_bytes(source: str, name: str) -> bytes:
    match = re.search(rf'const uint8_t {name}\[(\d+)\][^=]*=\s*((?:"(?:[^"\\]|\\.)*"\s*)+);', source)
    if not match:
        sys.exit(f"{name} not found in {FONTS_C}")
    data = b"".join(c_string_bytes(s) for s in re.findall(r'"((?:[^"\\]|\\.)*)"', match.group(2)))
    data += b"\0"  # the terminating NUL of the C string is part of the array
    if len(data) != int(match.group(1)):
        sys.exit(f"{name}: read {len(data)} bytes, expected {match.group(1)}")
    return data


def main() -> None:
    if not FONTS_C.exists():
        sys.exit(f"{FONTS_C} not found. Build the firmware once (cd firmware && pio run) to download U8g2.")
    source = FONTS_C.read_text(encoding="latin-1")

    lines = [
        "// Generated by tools/extract_u8g2_fonts.py from U8g2's u8g2_fonts.c. Do not edit.",
        "// Font data from U8g2 (https://github.com/olikraus/u8g2); each font keeps its own",
        "// license, listed in the U8g2 wiki (6x10 and 5x7 are the public domain X11 fonts).",
        "window.U8G2_FONT_DATA = {",
    ]
    for name in FONTS:
        encoded = base64.b64encode(font_bytes(source, name)).decode()
        lines.append(f'  {name}: "{encoded}",')
    lines.append("};")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({', '.join(FONTS)})")


if __name__ == "__main__":
    main()
